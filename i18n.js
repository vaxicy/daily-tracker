// ==================== i18n 工具函数 ====================
let currentLang = "zh";

function t(key, params = {}) {
  let text = (I18N[currentLang] && I18N[currentLang][key]) || key;
  Object.keys(params).forEach(k => {
    text = text.replace(`{${k}}`, params[k]);
  });
  return text;
}

function getLocale() {
  if (currentLang === "zh") return "zh-CN";
  if (currentLang === "es") return "es-ES";
  if (currentLang === "ja") return "ja-JP";
  if (currentLang === "ko") return "ko-KR";
  return "en-US";
}

function setLanguage(lang) {
  currentLang = lang;
  chrome.storage.local.set({ language: lang });
  applyI18n();
}

function loadLanguage(callback) {
  chrome.storage.local.get(["language"], (data) => {
    if (data.language) {
      // 用户曾手动切换过语言，优先使用存储值
      currentLang = data.language;
    } else {
      // 未设置时按浏览器语言自动识别，默认中文
      const browserLang = (navigator.language || (navigator.languages && navigator.languages[0]) || "zh").toLowerCase();
      currentLang = browserLang.startsWith("zh") ? "zh"
        : browserLang.startsWith("ja") ? "ja"
        : browserLang.startsWith("ko") ? "ko"
        : browserLang.startsWith("es") ? "es"
        : "en";
      // 首次识别后写回存储，保持后续一致
      chrome.storage.local.set({ language: currentLang });
    }
    if (callback) callback(currentLang);
  });
}

// ==================== 应用 i18n 到 DOM ====================
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const text = t(key);
    if (el.tagName === "INPUT" && el.placeholder !== undefined) {
      el.placeholder = text;
    } else if (el.tagName === "TITLE") {
      document.title = text;
    } else {
      el.textContent = text;
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    el.setAttribute("data-tooltip", t(key));
  });
  document.querySelectorAll("[data-i18n-range]").forEach(el => {
    const key = el.getAttribute("data-i18n-range");
    el.setAttribute("data-range", t(key));
  });
  // 更新 HTML lang 属性
  document.documentElement.lang = getLocale();

  // 通知其他模块 i18n 已更新
  document.dispatchEvent(new CustomEvent("i18nApplied"));
}
