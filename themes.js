// ==================== 自定义主题支持 ====================
// 设计：用户只选 4 个锚点色（背景主色/背景副色 + 按钮主色/按钮副色），其余变量由本模块推导。
// 约定：
// 1. 颜色严格按用户色卡 —— 4 个色原样使用，绝不自动"校正"；
// 2. 明暗（卡片/输入框/表面）由背景色自身亮度自动推导：浅底深字、深底浅字，用户不需要选；
// 3. 文字色按「按钮主色 + 背景色」现算：先取该明暗方向上的主色变体，再保证在背景上 ≥4.5:1；
// 4. 角标用「保饱和度压暗」而不是混黑，避免发灰。
// 这样用户永远搭不出「浅底浅字看不见」「角标灰扑扑」的破主题。

export const CUSTOM_THEME_PREFIX = "custom:";

function clamp01(v) {
  return Math.min(1, Math.max(0, v));
}

function hexToRgb(hex) {
  let h = String(hex || "").trim().replace("#", "");
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  if (h.length !== 6 || /[^0-9a-fA-F]/.test(h)) return { r: 0, g: 0, b: 0 };
  const n = parseInt(h, 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

function rgbToHex(r, g, b) {
  const f = (v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, "0");
  return `#${f(r)}${f(g)}${f(b)}`;
}

// 按比例把 a 混向 b（ratio=0 → a，ratio=1 → b）
export function mixHex(a, b, ratio) {
  const A = hexToRgb(a);
  const B = hexToRgb(b);
  const t = clamp01(ratio);
  return rgbToHex(A.r + (B.r - A.r) * t, A.g + (B.g - A.g) * t, A.b + (B.b - A.b) * t);
}

export function shadeHex(hex, ratio) {
  return mixHex(hex, "#000000", ratio);
}

export function tintHex(hex, ratio) {
  return mixHex(hex, "#ffffff", ratio);
}

export function hexWithAlpha(hex, alpha) {
  const { r, g, b } = hexToRgb(hex);
  return `rgba(${r},${g},${b},${alpha})`;
}

function rgbToHsl({ r, g, b }) {
  const R = r / 255, G = g / 255, B = b / 255;
  const max = Math.max(R, G, B), min = Math.min(R, G, B);
  const l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === R) h = ((G - B) / d + (G < B ? 6 : 0)) / 6;
    else if (max === G) h = ((B - R) / d + 2) / 6;
    else h = ((R - G) / d + 4) / 6;
  }
  return { h, s, l };
}

function hslToRgb({ h, s, l }) {
  if (s === 0) {
    const v = Math.round(l * 255);
    return { r: v, g: v, b: v };
  }
  const hue = (p, q, t) => {
    let tt = t;
    if (tt < 0) tt += 1;
    if (tt > 1) tt -= 1;
    if (tt < 1 / 6) return p + (q - p) * 6 * tt;
    if (tt < 1 / 2) return q;
    if (tt < 2 / 3) return p + (q - p) * (2 / 3 - tt) * 6;
    return p;
  };
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;
  return {
    r: Math.round(hue(p, q, h + 1 / 3) * 255),
    g: Math.round(hue(p, q, h) * 255),
    b: Math.round(hue(p, q, h - 1 / 3) * 255)
  };
}

