// ==================== 自定义主题支持 ====================
// 设计：用户只选 3 个锚点色（主色/副色/背景），其余 30 个变量由本模块推导。
// 约定：
// 1. 颜色严格按用户色卡 —— 背景色原样使用，不改写亮度；
// 2. 明暗（卡片/输入框/表面/文字）全部由背景色自身亮度自动推导：
//    浅色主题 → 深色字，深色主题 → 浅色字，用户不需要选；
// 3. 角标用「保饱和度压暗」而不是混黑，避免发灰。
// 这样用户永远搭不出「浅底浅字看不见」「角标灰扑扑」的破主题。

export const CUSTOM_THEME_PREFIX = "custom:";

function clamp01(v) {
  return Math.min(1, Math.max(0, v));
}

function hexToRgb(hex) {
  let h = String(hex || "").trim().replace("#", "");
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  if (h.length !== 6 || /[^0-9a-fA-F]/.test(h)) return { r: 0, g: 0, b: 0 };
  const n = parseInt(h, 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

function rgbToHex(r, g, b) {
  const f = (v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, "0");
  return `#${f(r)}${f(g)}${f(b)}`;
}

// 按比例把 a 混向 b（ratio=0 → a，ratio=1 → b）
export function mixHex(a, b, ratio) {
  const A = hexToRgb(a);
  const B = hexToRgb(b);
  const t = clamp01(ratio);
  return rgbToHex(A.r + (B.r - A.r) * t, A.g + (B.g - A.g) * t, A.b + (B.b - A.b) * t);
}

export function shadeHex(hex, ratio) {
  return mixHex(hex, "#000000", ratio);
}

export function tintHex(hex, ratio) {
  return mixHex(hex, "#ffffff", ratio);
}

export function hexWithAlpha(hex, alpha) {
  const { r, g, b } = hexToRgb(hex);
  return `rgba(${r},${g},${b},${alpha})`;
}

function rgbToHsl({ r, g, b }) {
  const R = r / 255, G = g / 255, B = b / 255;
  const max = Math.max(R, G, B), min = Math.min(R, G, B);
  const l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === R) h = ((G - B) / d + (G < B ? 6 : 0)) / 6;
    else if (max === G) h = ((B - R) / d + 2) / 6;
    else h = ((R - G) / d + 4) / 6;
  }
  return { h, s, l };
}

function hslToRgb({ h, s, l }) {
  if (s === 0) {
    const v = Math.round(l * 255);
    return { r: v, g: v, b: v };
  }
  const hue = (p, q, t) => {
    let tt = t;
    if (tt < 0) tt += 1;
    if (tt > 1) tt -= 1;
    if (tt < 1 / 6) return p + (q - p) * 6 * tt;
    if (tt < 1 / 2) return q;
    if (tt < 2 / 3) return p + (q - p) * (2 / 3 - tt) * 6;
    return p;
  };
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;
  return {
    r: Math.round(hue(p, q, h + 1 / 3) * 255),
    g: Math.round(hue(p, q, h) * 255),
    b: Math.round(hue(p, q, h - 1 / 3) * 255)
  };
}

// 角标文字用的深色（极浅角标底上比纯黑柔和）
export const BADGE_DARK_TEXT = "#1F2937";

// 与深色字的对比度
export function contrastWithDark(hex) {
  return (relativeLuminance(hex) + 0.05) / (relativeLuminance(BADGE_DARK_TEXT) + 0.05);
}

// 角标文字色：默认白字，浅底色改用深色字（底色仍然原样，不压暗）。
// 分界：白字对比 < 1.9（约等于亮度 > 0.50）就用深色字。
// 参考实测：浅薰衣草 #D5BAE8 = 1.75 → 深字；亮蓝 #30AFFF = 2.41 → 白字；
//          藕紫 #8D5F8C = 5.06 → 白字；更浅的（1.04~1.24）也是深字。
const BADGE_DARK_TEXT_WHITE_CONTRAST_MAX = 1.9;
export function badgeTextColorOn(bg) {
  return contrastWithWhite(bg) < BADGE_DARK_TEXT_WHITE_CONTRAST_MAX ? BADGE_DARK_TEXT : "#ffffff";
}

// 填充色（按钮/选中块的底色）上的文字色：白字和深字里取对比更高的那个。
// 注意与角标不同 —— 角标按用户偏好"默认白字"，按钮则以清晰为准（浅色填充必须换深字）。
export function fillTextColorOn(bg) {
  return contrastWithWhite(bg) >= contrastWithDark(bg) ? "#ffffff" : BADGE_DARK_TEXT;
}

// 角标底色：永远【原样用主色】，一个色阶都不改（用户明确要求直接跟随主色）。
export function badgeColorFor(primary) {
  const { r, g, b } = hexToRgb(primary);
  return rgbToHex(r, g, b);
}

// WCAG 相对亮度（用于角标文字取黑/白、角标底色压暗收敛）
export function relativeLuminance(hex) {
  const { r, g, b } = hexToRgb(hex);
  const lin = (v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}

// 明暗判定：直接比较「白字 / 深字」哪个在这个色上更清楚，谁更清楚就按哪一边算。
// 不要用亮度阈值硬卡 —— 粉、紫、浅薰衣草这类"看着很浅但 WCAG 亮度偏低"的色
// 会被 0.62 这种阈值误判成深色（用户截图：浅紫背景却套上了深色卡片/按钮/开关）。
// 这个判据与 fillTextColorOn 完全一致，所以"主题明暗"和"文字该用什么色"永不打架。
export function isLightColor(hex) {
  return contrastWithWhite(hex) < contrastWithDark(hex);
}

// 两色对比度
export function contrastRatio(a, b) {
  const l1 = relativeLuminance(a);
  const l2 = relativeLuminance(b);
  return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
}

// 把 color 沿「明度」方向逐档微调，直到在 surface 上达到 target 对比度。
// 关键：在 HSL 里只改明度、保留色相与饱和度 —— 直接往黑/白里混会让颜色变灰发浑
// （用户反馈"黑不溜秋、不符合主题选色"），保留饱和度才能看出还是自己选的那个色系。
export function readableOn(color, surface, target = 4.5) {
  if (contrastRatio(color, surface) >= target) return color;
  const rgb = hexToRgb(color);
  const hsl = rgbToHsl(rgb);
  // 往哪个方向调？看「白 / 黑」谁在这个底色上对比更高 —— 不能拿底色亮度卡 0.5：
  // 亮蓝 (#30AFFF, 亮度 0.385) 其实该压暗，按 0.5 判会一路走到白、对比反而更差。
  const toLight = contrastRatio("#ffffff", surface) > contrastRatio("#000000", surface);
  let l = hsl.l;
  let out = color;
  for (let i = 0; i < 60; i++) {
    l = Math.min(1, Math.max(0, l + (toLight ? 0.03 : -0.03)));
    const c = hslToRgb({ h: hsl.h, s: hsl.s, l });
    out = rgbToHex(c.r, c.g, c.b);
    if (contrastRatio(out, surface) >= target) break;
    if (l <= 0 || l >= 1) break;
  }
  return out;
}

// 自定义主题该挂哪个 data-theme：
//   深色 → "dark"（复用 popup.html 里现成的 dark 覆盖层，卡片/输入框/按钮等才有深色规则）
//   浅色 → "custom"（不套任何主题覆盖，纯靠变量驱动）
// 依据【实际背景亮度】推导，不依赖存下来的字段 —— 旧数据/手改数据也能正确挂载。
export function customThemeDataAttr(rec) {
  if (!rec || !rec.custom) return null;
  const bg =
    (rec.vars && rec.vars["--bg"]) ||
    (rec.roles && rec.roles.bg) ||
    (rec.anchors && (rec.anchors.bg || (rec.anchors.roles && rec.anchors.roles.bg)));
  return bg && !isLightColor(bg) ? "dark" : "custom";
}

// 与白字的对比度（角标默认白字）
function contrastWithWhite(hex) {
  return 1.05 / (relativeLuminance(hex) + 0.05);
}

// ==================== 调色板 → 角色分配（智能分配，不需要用户指定谁是谁） ====================
// 用户最多给 4 个颜色，谁当背景/主色/副色/点缀由对比度 + 饱和度测试决定：
//   · 背景：挑"像画布"的那个（够淡或够深、且不太艳）；一个都不像就由主色淡出来 —— 绝不让艳色当全屏底
//   · 主色：剩下里最鲜艳的（撞色时它就是主角）
//   · 副色：剩下里与主色色相差最大的（撞色优先，两个颜色才"撞"得起来）
//   · 点缀色（第 4 个）：剩下的那个，用在经期这类需要第三种颜色的地方
// 已定好的角色（老数据 / 上次的分配结果）只要色值还在调色板里就沿用，观感不会跳。
function normalizeHex(v) {
  const s = String(v || "");
  if (!/^#[0-9a-fA-F]{6}$/.test(s)) return null;
  const { r, g, b } = hexToRgb(s);
  return rgbToHex(r, g, b);
}

// 彩度（max-min）：比 HSL 的 S 稳 —— HSL 的 S 在接近纯白/纯黑时会虚高到 1
function chromaOf(hex) {
  const { r, g, b } = hexToRgb(hex);
  return (Math.max(r, g, b) - Math.min(r, g, b)) / 255;
}

// 注意：本文件的 HSL 里 h 是 0~1（不是 0~360），取色相距离要在这个刻度上环绕
function hueOf(hex) {
  return rgbToHsl(hexToRgb(hex)).h;
}

function hueDistance(a, b) {
  const d = Math.abs(hueOf(a) - hueOf(b));
  return Math.min(d, 1 - d) * 360;
}

// "像画布"的颜色：要么够淡、要么够深，而且不太艳（艳色当全屏底色会刺眼）
function isCanvasColor(hex) {
  const l = relativeLuminance(hex);
  return chromaOf(hex) <= 0.35 && (l >= 0.55 || l <= 0.25);
}

function canvasScore(hex) {
  return Math.abs(relativeLuminance(hex) - 0.5) * 2 * (1 - chromaOf(hex) * 0.7);
}

function pickBest(list, score) {
  return list.reduce((best, c) => (score(c) > score(best) ? c : best), list[0]);
}

export function resolvePalette(anchors = {}) {
  let palette = Array.isArray(anchors.palette) ? anchors.palette.map(normalizeHex).filter(Boolean) : [];
  if (!palette.length) {
    // 老格式：{primary, secondary, bg} → 当成一串颜色看待
    palette = [anchors.primary, anchors.secondary, anchors.accent, anchors.bg].map(normalizeHex).filter(Boolean);
  }
  palette = palette.filter((c, i) => palette.findIndex((x) => x.toLowerCase() === c.toLowerCase()) === i);
  if (palette.length === 1) palette = palette.concat(tintHex(palette[0], 0.88));
  if (!palette.length) palette = ["#0b6bff", "#eaf5ff"];

  // 继承已有角色（色值必须仍在调色板里）
  const prev = anchors.roles || {};
  const keep = {};
  ["bg", "primary", "secondary", "accent"].forEach((role) => {
    const want = normalizeHex(prev[role]) || normalizeHex(anchors[role]);
    if (!want) return;
    const hit = palette.find((c) => c.toLowerCase() === want.toLowerCase());
    if (hit) keep[role] = hit;
  });
  const free = palette.filter((c) => !Object.values(keep).some((k) => k.toLowerCase() === c.toLowerCase()));
  const take = (c) => {
    const i = free.indexOf(c);
    if (i >= 0) free.splice(i, 1);
    return c;
  };

  if (!keep.bg) {
    const cands = free.filter(isCanvasColor);
    if (cands.length) keep.bg = take(pickBest(cands, canvasScore));
  }
  if (!keep.primary) {
    // 没有空闲颜色时（比如用户把"主色"那个色块删掉了）就从别的角色里"抢"一个回来，
    // 否则主色会退化成背景色（两者同色 → 整个主题失去重点）
    const pool = free.length ? free : palette.filter((c) => c !== keep.bg);
    if (pool.length) {
      const bgRef = keep.bg || null;
      const chosen = pickBest(
        pool,
        (c) => chromaOf(c) * 2 + (bgRef ? Math.min(contrastRatio(c, bgRef), 6) / 6 : 0)
      );
      ["secondary", "accent"].forEach((r) => {
        if (keep[r] === chosen) delete keep[r];
      });
      keep.primary = take(chosen);
    }
  }
  if (!keep.secondary && free.length) {
    // 撞色优先：与主色色相差越大越可能被选；乘彩度权重，避免把灰度色当成"撞色"
    keep.secondary = take(
      pickBest(free, (c) => hueDistance(c, keep.primary) * (0.3 + Math.min(chromaOf(c), 0.5)))
    );
  }
  if (!keep.accent && free.length) keep.accent = take(free[0]);

  const primary = keep.primary || palette[0];
  const secondary = keep.secondary || tintHex(primary, 0.3);
  const bg = keep.bg || tintHex(primary, 0.88);
  return {
    palette,
    primary,
    secondary,
    bg,
    accent: keep.accent || null,
    // 只有"确实是调色板里的颜色"才回存角色；派生出来的不存，
    // 否则以后改主色时背景/副色不会跟着变（会留着旧值打架）
    roles: {
      primary,
      ...(keep.secondary ? { secondary: keep.secondary } : {}),
      ...(keep.accent ? { accent: keep.accent } : {}),
      ...(keep.bg ? { bg: keep.bg } : {})
    }
  };
}

// 随机调色板（编辑器「随机」按钮）：先随机一个色相与明暗模式，再按
// 「背景 + 主色 + 撞色副色(+点缀色)」生成 —— 不是纯随机 RGB，取值都落在舒服的区间里，
// 所以出来的配色天生协调，且背景一定"像画布"（能被分配算法认出来）。
export function randomPalette() {
  const rnd = (a, b) => a + Math.random() * (b - a);
  const rndInt = (a, b) => Math.floor(rnd(a, b + 1));
  // 色相按"度数"写更直观，进来换算成 0~1（hslToRgb 用的是这个刻度）
  const hsl = (deg, s, l) => {
    const c = hslToRgb({ h: (((deg % 360) + 360) % 360) / 360, s: clamp01(s), l: clamp01(l) });
    return rgbToHex(c.r, c.g, c.b);
  };
  const dark = Math.random() < 0.5; // 深色 / 浅色主题各一半
  const baseHue = rndInt(0, 359);
  const dir = Math.random() < 0.5 ? 1 : -1;

  // 背景：同色相的极淡/极深色，饱和度压低（别抢戏，也不会变成艳色底）
  const bg = dark
    ? hsl(baseHue + rndInt(-40, 40), rnd(0.18, 0.4), rnd(0.10, 0.20))
    : hsl(baseHue + rndInt(-40, 40), rnd(0.10, 0.35), rnd(0.88, 0.96));
  // 主色：同色相家族里"能站住"的那个明度（深底要亮、浅底要沉）
  const mainL = dark ? rnd(0.64, 0.78) : rnd(0.42, 0.56);
  const primary = hsl(baseHue, rnd(0.55, 0.9), mainL);
  // 副色：撞色 —— 色相偏 100~200 度（这就是"两个颜色一起撞色"）
  const secondary = hsl(baseHue + dir * rndInt(100, 200), rnd(0.5, 0.9), mainL + rnd(-0.08, 0.08));

  const palette = [primary, secondary];
  // 一半概率再给一个点缀色（用在经期这类需要第三色的地方）
  if (Math.random() < 0.5) {
    palette.push(hsl(baseHue - dir * rndInt(120, 200), rnd(0.5, 0.85), mainL + rnd(-0.06, 0.06)));
  }
  palette.push(bg); // 背景放最后：前几个是"颜色"，最后一个是画布
  return palette;
}

// 由调色板（最多 4 个颜色）生成完整主题（31 个 CSS 变量 + dot + bgGradient）
// anchors 兼容三种形态：{palette, roles}（新）/ {primary, secondary, bg}（老）/ {primary, bg}
export function buildCustomTheme(anchors = {}) {
  const pal = resolvePalette(anchors);
  const p = pal.primary;
  const s = pal.secondary;
  const g = pal.bg;

  // 背景明暗【完全由用户选的背景色决定】，不再由开关改写用户色卡
  const bgIsDark = !isLightColor(g);
  // 文字深浅【全自动】：深色主题出浅色字，浅色主题出深色字（用户无需选择）
  const darkText = !bgIsDark;

  const text = darkText ? shadeHex(p, 0.68) : tintHex(p, 0.9);
  const primary2 = tintHex(p, 0.45);
  const secondary2 = tintHex(s, 0.4);
  // 卡片跟着背景走（浅底更浅、深底更亮），不再混主色以免偏离用户色卡
  const cardBg = bgIsDark ? tintHex(g, 0.12) : tintHex(g, 0.62);
  // 经期色：调色板给了第 4 个颜色就用它（撞色），否则沿用"粉与主色混一档"
  const period = pal.accent || mixHex("#E0679E", p, 0.2);
  const poop = darkText ? "#8A6E4A" : tintHex("#8A6E4A", 0.15);
  // 角标：保饱和度压暗（混黑会发灰）
  const badge = badgeColorFor(p);

  // 语义色只当「填充」用时按原色（保饱和、保住用户色卡）；
  // 但当「文字/图标」用时（日历标题、统计数字、周几…）必须保证在卡片底色上能看清，
  // 所以在深色主题里往白走、浅色主题里往黑走，逐档微调到 4.5:1。预设主题不定义这组变量，
  // CSS 里都用 var(--xxx-text, var(--xxx)) 回退，所以 38 个预设的观感完全不变。
  const asText = (c) => readableOn(c, cardBg);
  // 等级阶梯的基准色（"最强"那一档）：先把主色调到在卡片上可读（≥4.5:1），再往卡片方向逐档混。
  // readableOn 只改明度、保留色相与饱和度，所以浅淡主色也能排出可见的 4 档而不是一片灰。
  const lvBase = asText(p);
  // 四档从卡片底单调递进：浅色主题越深=喝得越多，深色主题越亮=喝得越多。
  // 全部由同一个基准色推出来，保证单调、不会出现"第 5 档比第 4 档还浅"的错乱。
  const lvTint = (r) => mixHex(cardBg, lvBase, r);
  // 浅色主题的档位停在"深色数字仍舒服"的范围内（否则最深的格子上深字会发虚）；
  // 深色主题则要走到浅色区，好让深色字在每一档都清楚。
  const lv0c = lvTint(bgIsDark ? 0.15 : 0.10);
  const lv1c = lvTint(bgIsDark ? 0.45 : 0.30);
  const lv2c = lvTint(bgIsDark ? 0.65 : 0.50);
  const lv3c = lvTint(bgIsDark ? 0.85 : 0.68);

  const vars = {
    "--text": text,
    "--muted": hexWithAlpha(text, 0.6),
    "--primary": p,
    "--primary2": primary2,
    "--primary-glow": hexWithAlpha(p, 0.45),
    "--secondary": s,
    "--secondary2": secondary2,
    "--eat": p,
    "--eat2": primary2,
    "--pee": s,
    "--pee2": secondary2,
    "--poop": poop,
    "--poop2": darkText ? "#6E5433" : tintHex("#6E5433", 0.15),
    // 喝水等级色阶（日历方块 + 图例）。
    // 关键：不能简单用「主色叠 N% 透明度」——当主色和卡片底色亮度接近时（深色主题常见），
    // 25%/50%/75% 三档混出来几乎一样，图例和日历就糊成一片。
    // 所以按亮度目标生成，保证相邻档位有可见跃升，并且都避开卡片底色附近（否则那一档会"消失"）。
    "--lv0": lv0c,
    "--lv1": lv1c,
    "--lv2": lv2c,
    "--lv3": lv3c,
    // lv4（满杯）：在同一个方向上再进一档（从 lv3 渐变到基准色 lvBase）。
    // 不能再用「主色→primary2」的渐变 —— 浅淡主色时它会比 lv3 更浅，色阶在第 5 档"跳回去"，
    // 图例和日历看着就错乱（用户反馈过）。
    "--lv4": `linear-gradient(135deg, ${lv3c}, ${lvBase})`,
    // 等级块上的数字颜色：按"实际填充色"取对比更高的白/深字。
    // lv4 是渐变（lv3 → 基准色），要按渐变最深的那一端判，所以单独一路。
    "--lv-text": fillTextColorOn(lv2c),
    "--lv-text-strong": fillTextColorOn(lv3c),
    "--lv-text-max": fillTextColorOn(lvBase),
    "--period": period,
    "--period2": tintHex(period, 0.45),
    "--period-glow": hexWithAlpha(period, 0.42),
    // 当文字用的语义色（深底提亮 / 浅底压暗，保证可读）
    "--primary-text": lvBase,
    "--secondary-text": asText(s),
    "--eat-text": lvBase,
    "--pee-text": asText(s),
    "--poop-text": asText(poop),
    "--period-text": asText(period),
    // 填充色上的文字色（浅填充自动换深字，避免白字糊在浅底上）
    "--on-primary": fillTextColorOn(p),
    "--on-secondary": fillTextColorOn(s),
    "--on-eat": fillTextColorOn(p),
    "--on-pee": fillTextColorOn(s),
    "--on-poop": fillTextColorOn(poop),
    "--on-period": fillTextColorOn(period),
    "--card-bg": cardBg,
    "--card-border": hexWithAlpha(p, 0.16),
    "--input-bg": darkText ? "rgba(255,255,255,0.75)" : "rgba(255,255,255,0.10)",
    "--modal-bg": cardBg,
    "--tooltip-bg": cardBg,
    "--sidebar-bg": hexWithAlpha(cardBg, 0.97),
    "--hover-bg": darkText ? hexWithAlpha(p, 0.08) : "rgba(255,255,255,0.08)",
    "--day-hover": darkText ? hexWithAlpha(p, 0.12) : "rgba(255,255,255,0.12)",
    "--day-today": hexWithAlpha(p, darkText ? 0.18 : 0.34),
    "--scrollbar-color": p,
    "--scrollbar-hover": shadeHex(p, 0.15),
    "--bg": g,
    "--badge": badge,
    "--toast-bg": "color-mix(in srgb, var(--primary) 85%, black)",
    "--toast-text": "#ffffff"
  };

  return {
    custom: true,
    // 复用现成的 dark 覆盖规则，依据「实际背景」而不是开关
    dataTheme: bgIsDark ? "dark" : "custom",
    // 实际生效的文字方向（自动推导，浅底深字 / 深底浅字）
    darkText,
    // 存用户给的调色板 + 分配结果；派生出来的（不在调色板里的）角色不回存
    anchors: { palette: pal.palette, roles: pal.roles },
    vars,
    dot: `linear-gradient(135deg,${p},${primary2},${s})`,
    bgGradient: bgIsDark
      ? `linear-gradient(150deg, ${shadeHex(g, 0.3)} 0%, ${g} 55%, ${mixHex(g, p, 0.14)} 100%)`
      : `linear-gradient(150deg, ${tintHex(g, 0.6)} 0%, ${g} 55%, ${mixHex(g, p, 0.18)} 100%)`
  };
}

// 统一解析：自定义主题优先，其次预设；都找不到返回 null
export function getThemePreset(id, customThemes) {
  if (customThemes && Object.prototype.hasOwnProperty.call(customThemes, id)) {
    return customThemes[id];
  }
  return THEME_PRESETS[id] || null;
}

// 显示名：预设走 i18n key，自定义直接用用户起的名字
export function themeDisplayName(id, customThemes) {
  const rec = customThemes && customThemes[id];
  if (rec && rec.label) return rec.label;
  const preset = THEME_PRESETS[id];
  return preset ? preset.name : id;
}
